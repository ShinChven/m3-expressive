// Generates src/styles/baseline-scheme.css: the static M3 baseline colors used before
// (or without) ThemeProvider. Run with `npm run gen:baseline -w material-design-3-expressive-components`.
import { existsSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import { registerHooks } from 'node:module'
import { fileURLToPath } from 'node:url'

// @material/material-color-utilities ships some extensionless ESM imports and our
// sources use bundler-style imports; resolve both the way Vite does.
registerHooks({
  resolve(specifier, context, next) {
    try {
      return next(specifier, context)
    } catch (error) {
      if (!specifier.startsWith('.') || !context.parentURL) throw error
      for (const ext of ['.ts', '.tsx', '.js']) {
        const url = new URL(specifier + ext, context.parentURL)
        if (existsSync(fileURLToPath(url))) return next(url.href, context)
      }
      throw error
    }
  },
})

const { createThemeCss, BASELINE_SEED } = await import('../src/theme/scheme.ts')

const css = createThemeCss({ seed: BASELINE_SEED, contrast: 'auto', selector: ':root' })
  .replaceAll('}', '}\n')
  .replaceAll(';', ';\n  ')
  .replaceAll('{', ' {\n  ')
const header =
  '/* Generated by scripts/gen-baseline.mjs from the M3 baseline seed. Do not edit. */\n'
const out = fileURLToPath(new URL('../src/styles/baseline-scheme.css', import.meta.url))
await writeFile(out, header + css)
console.log(`wrote ${out}`)
